-- 10. Funciones: solapes (los recalcula cada carga) y registro de eventos de citas
-- ---------------------------------------------------------------------------------------------------------------------
create or replace function agenda.recalcular_solapes() returns integer
language plpgsql set search_path = pg_catalog, agenda as $$
declare n integer;
begin
  with calc as (
    select c.id,
           (coalesce(c.anulada, true) is false and c.desaparecida_at is null and c.hora_inicio is not null and c.hora_fin is not null
            and exists (select 1 from agenda.citas o
                         where o.id <> c.id and o.fecha = c.fecha and o.profesional_id is not distinct from c.profesional_id
                           and o.anulada is false and o.desaparecida_at is null
                           and o.hora_inicio < c.hora_fin and c.hora_inicio < o.hora_fin)) as solapa
      from agenda.citas c)
  update agenda.citas c set solape_importado = calc.solapa
    from calc
   where calc.id = c.id and c.solape_importado is distinct from calc.solapa;
  get diagnostics n = row_count;
  return n;
end $$;

create or replace function agenda.tg_cita_eventos() returns trigger
language plpgsql set search_path = pg_catalog, agenda as $$
declare corr uuid := nullif(current_setting('agenda.corrida_id', true), '')::uuid;
begin
  if new.estado_id is distinct from old.estado_id then
    insert into agenda.cita_eventos (cita_id, corrida_id, campo, antes, despues)
    values (new.id, corr, 'estado',
            jsonb_build_object('estado_id', old.estado_id, 'dentalink_actualizado_at', old.dentalink_actualizado_at),
            jsonb_build_object('estado_id', new.estado_id, 'dentalink_actualizado_at', new.dentalink_actualizado_at));
  end if;
  if (new.fecha, new.hora_inicio, new.duracion_min) is distinct from (old.fecha, old.hora_inicio, old.duracion_min) then
    insert into agenda.cita_eventos (cita_id, corrida_id, campo, antes, despues)
    values (new.id, corr, 'fecha_hora',
            jsonb_build_object('fecha', old.fecha, 'hora_inicio', old.hora_inicio, 'duracion_min', old.duracion_min),
            jsonb_build_object('fecha', new.fecha, 'hora_inicio', new.hora_inicio, 'duracion_min', new.duracion_min));
  end if;
  if new.desaparecida_at is not null and old.desaparecida_at is null then
    insert into agenda.cita_eventos (cita_id, corrida_id, campo, antes, despues) values (new.id, corr, 'desaparecida', null, null);
  elsif new.desaparecida_at is null and old.desaparecida_at is not null then
    insert into agenda.cita_eventos (cita_id, corrida_id, campo, antes, despues) values (new.id, corr, 'reaparecida', null, null);
  end if;
  return new;
end $$;

drop trigger if exists citas_eventos_tg on agenda.citas;
create trigger citas_eventos_tg after update on agenda.citas for each row execute function agenda.tg_cita_eventos();

-- Lo que el bot leería en lugar de GET /pacientes?q={"celular":{"lk":…}} (fichas vigentes por celular, sin duplicados)
create or replace view agenda.fichas_por_celular with (security_invoker = true) as
select celular_normalizado,
       count(*)::integer as fichas,
       array_agg(id order by id) as ficha_ids,
       bool_or(es_menor) as alguna_menor
  from agenda.fichas
 where celular_normalizado is not null and desaparecida_at is null and duplicado_de is null and habilitado is not false
 group by celular_normalizado;

