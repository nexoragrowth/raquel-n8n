-- 3. Fichas de pacientes (fase b mínima / c completa / d observaciones)
-- ---------------------------------------------------------------------------------------------------------------------
create table if not exists agenda.fichas (
  id bigint generated by default as identity (start with 10000000) primary key,
  dentalink_id bigint,
  -- fase b (C12): lo mínimo para vincular contactos y familias
  habilitado boolean,
  celular_normalizado text check (celular_normalizado is null or celular_normalizado ~ '^[0-9]{8,15}$'),
  celular_estado text check (celular_estado in ('ok', 'normalizado', 'vacio', 'lid', 'falso', 'sintetico', 'sin_codigo_area', 'extranjero', 'invalido')),
  es_menor boolean,
  fecha_afiliacion date,
  origen_probable text check (origen_probable in ('staff', 'bot_v6', 'bot_v7', 'panel', 'propia')),
  duplicado_de bigint references agenda.fichas (id) deferrable initially deferred,
  duplicado_regla text check (duplicado_regla in ('mismo_documento', 'mismo_nombre_y_nacimiento', 'mismo_nombre_y_celular', 'manual')),
  celular_compartido_n integer,
  calidad text[] not null default '{}',
  -- fase c: identidad y contacto completos (requiere ampliar C12)
  nombre text, apellidos text, nombre_social text, nombre_normalizado text,
  documento text, documento_normalizado text,
  documento_estado text check (documento_estado in ('ok', 'dudoso', 'vacio', 'falso', 'invalido', 'pasaporte_u_otro')),
  tipo_documento integer, es_pasaporte boolean, fecha_nacimiento date, sexo text, id_genero integer,
  celular text, telefono text, telefono_normalizado text, email text, email_normalizado text,
  direccion text, ciudad text, comuna text, numero_ficha text,
  fecha_deshabilitacion date, usuario_deshabilitacion_dentalink_id bigint, es_carga boolean, tiene_cargas boolean,
  -- fase d (texto libre, se trata como clínico)
  observaciones text,
  espejo_creado_at timestamptz not null default now(), espejo_actualizado_at timestamptz, espejo_corrida_id uuid, desaparecida_at timestamptz,
  constraint fichas_dentalink_uk unique (dentalink_id),
  constraint fichas_id_chk check (dentalink_id is null or (id = dentalink_id and dentalink_id between 0 and 9999999)),
  constraint fichas_duplicado_chk check (duplicado_de is null or duplicado_de <> id),
  constraint fichas_duplicado_regla_chk check ((duplicado_de is null) = (duplicado_regla is null))
);
create index if not exists fichas_celular_idx on agenda.fichas (celular_normalizado) where desaparecida_at is null;
create index if not exists fichas_documento_idx on agenda.fichas (documento_normalizado) where documento_normalizado is not null;
create index if not exists fichas_nombre_idx on agenda.fichas (nombre_normalizado) where nombre_normalizado is not null;
create index if not exists fichas_duplicado_idx on agenda.fichas (duplicado_de) where duplicado_de is not null;
comment on column agenda.fichas.duplicado_de is 'Ficha canónica si esta es un duplicado probable (marca; nada se borra ni se fusiona solo).';
comment on column agenda.fichas.origen_probable is 'bot_v6/bot_v7 = alta hecha por el bot (inferido por los campos que manda cada alta); staff = resto.';

