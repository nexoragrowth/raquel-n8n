create table if not exists agenda.citas (
  id bigint generated by default as identity (start with 10000000) primary key,
  dentalink_id bigint,
  fecha date, hora_inicio time, hora_fin time, duracion_min integer,
  estado_id bigint references agenda.estados_cita (id) deferrable initially deferred,
  anulada boolean,                      -- copia de estados_cita.anulacion (la usará el EXCLUDE de la agenda propia)
  estado_confirmacion integer, estado_anulacion integer,
  sucursal_id bigint references agenda.sucursales (id) deferrable initially deferred,
  profesional_id bigint references agenda.profesionales (id) deferrable initially deferred,
  sillon_id bigint references agenda.sillones (id) deferrable initially deferred,
  motivo_atencion text, tratamiento_sin_asignar boolean,
  dentalink_actualizado_at timestamp,   -- fecha_actualizacion de Dentalink (hora local de la cuenta); base de la sincronización incremental
  origen_inferido text check (origen_inferido in ('bot_v7', 'bot_v6', 'panel', 'staff_o_desconocido', 'propia')),
  solape_importado boolean not null default false,   -- se pisa con otra cita no anulada del mismo profesional (histórico, NO sobreturno)
  fuera_de_horario boolean,
  calidad text[] not null default '{}',
  -- fase b
  ficha_id bigint references agenda.fichas (id) deferrable initially deferred,
  paciente_dentalink_id bigint,
  -- fase c
  tratamiento_id bigint references agenda.tratamientos (id) deferrable initially deferred,
  tratamiento_dentalink_id bigint,
  -- fase d
  comentarios text,
  espejo_creado_at timestamptz not null default now(), espejo_actualizado_at timestamptz, espejo_corrida_id uuid, desaparecida_at timestamptz,
  constraint citas_dentalink_uk unique (dentalink_id),
  constraint citas_id_chk check (dentalink_id is null or (id = dentalink_id and dentalink_id between 0 and 9999999)),
  constraint citas_horas_chk check (hora_inicio is null or hora_fin is null or hora_fin >= hora_inicio)
);
create index if not exists citas_fecha_idx on agenda.citas (fecha, hora_inicio) where desaparecida_at is null;
create index if not exists citas_profesional_fecha_idx on agenda.citas (profesional_id, fecha);
create index if not exists citas_ficha_idx on agenda.citas (ficha_id) where ficha_id is not null;
create index if not exists citas_estado_idx on agenda.citas (estado_id);
create index if not exists citas_actualizado_idx on agenda.citas (dentalink_actualizado_at);

