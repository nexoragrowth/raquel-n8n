-- =====================================================================================================================
-- sql/2026-10-20_dentalink_espejo.sql  -  Espejo completo y curado de Dentalink en el Supabase v3 (esquema `agenda`)
-- Plan: docs/plan-migracion-dentalink-2026-10-20.md. Lo carga scripts/migrar_dentalink.py (simulación por defecto; --apply carga).
-- Modelo: docs/plan-contactos-conversion-dentalink-2026-10-13.md Anexo A (agenda.*, ids espejados = id de Dentalink, propios
-- desde 10.000.000) y Anexo B (permisos).
--
-- ADITIVA E IDEMPOTENTE: no toca ninguna tabla existente (solo crea el esquema `agenda`); se puede correr dos veces.
-- Correr como postgres. Una sola transacción: si algo falla, no queda nada.
--
-- PERMISOS: RLS activo en TODAS las tablas, sin policies. anon/authenticated: nada (ni USAGE del esquema). service_role:
-- SELECT/INSERT/UPDATE (nunca DELETE: el espejo marca, no borra). El esquema NO se agrega a "Exposed schemas" de PostgREST.
--
-- IDS: cada fila espejada tiene id = dentalink_id (único, < 10.000.000). Las filas propias que se creen después del corte
-- toman id desde 10.000.000 (identity) y dentalink_id NULL (o el de Dentalink si hay escritura inversa).
-- FASES (qué columnas llena el script, --fase; ver su docstring). En los comentarios de abajo: a = ocupacion (sin datos de
-- pacientes, ANTES del contrato) · b = ficha_minima (C12 b) · c = pacientes (datos personales y administrativos completos, DESPUÉS
-- del contrato SEG-17) · d = clinica (historia clínica). Las columnas de una fase no cargada quedan NULL.
-- =====================================================================================================================
begin;
set local lock_timeout = '3s';
set local statement_timeout = '120s';

create schema if not exists agenda;
comment on schema agenda is 'Agenda propia: espejo curado de Dentalink (hasta el corte) y luego sistema propio. No exponer en PostgREST.';

-- ---------------------------------------------------------------------------------------------------------------------
-- 0. Control: versión, configuración y corridas del espejo
-- ---------------------------------------------------------------------------------------------------------------------
create table if not exists agenda.esquema_version (
  version     text primary key,
  aplicado_at timestamptz not null default now(),
  nota        text
);

create table if not exists agenda.config (
  clave           text primary key,
  valor           text not null,
  actualizado_at  timestamptz not null default now(),
  actualizado_por text
);
-- backend: de dónde leen/escriben el bot y el panel ('dentalink' hasta el corte; 'agenda' después). Nunca cambia por defecto.
insert into agenda.config (clave, valor, actualizado_por) values
  ('backend', 'dentalink', 'migracion_2026-10-20'),
  ('espejo_ultimas_fases', '', 'migracion_2026-10-20')
on conflict (clave) do nothing;

create table if not exists agenda.sync_corridas (
  id                uuid primary key,
  inicio            timestamptz not null default now(),
  fin               timestamptz,
  tipo              text not null check (tipo in ('completa', 'incremental')),
  fases             text[] not null,
  desde             text,
  estado            text not null check (estado in ('en_curso', 'ok', 'error')),
  pedidos_dentalink integer,
  conteos           jsonb not null default '{}'::jsonb,   -- solo agregados (filas por tabla)
  avisos            jsonb not null default '[]'::jsonb,
  script_version    text,
  created_at        timestamptz not null default now()
);
create index if not exists sync_corridas_inicio_idx on agenda.sync_corridas (inicio desc);

